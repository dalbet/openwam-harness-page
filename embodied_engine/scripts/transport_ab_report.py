#!/usr/bin/env python
"""One control run against one intervention run, same scene and same noise rule.

The comparison is deliberately narrow. Both arms pin the same ``scene_seed``
and the same ``policy_seed``, so the initial diffusion noise of every request
is generated by the same rule; that does **not** make the two runs consume the
same noise arrays, because the number of requests differs once the executed
window changes. This report states that instead of pretending the two
trajectories share an input stream.

    python scripts/transport_ab_report.py \
        --arm control=/path/control.json --arm intervention=/path/int.json \
        --out /path/ab.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

PROJECT = Path(__file__).resolve().parents[1]
if str(PROJECT / "scripts") not in sys.path:
    sys.path.insert(0, str(PROJECT / "scripts"))

import transport_phase_compare as phase_compare  # noqa: E402


def step_rows(record: dict[str, Any]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for index, step in enumerate(record.get("steps") or [], start=1):
        rows.append(
            {
                "index": index,
                "step_id": step.get("step_id"),
                "task_key": (step.get("step") or {}).get("step_key") or (step.get("step") or {}).get("task_key"),
                "ok": step.get("ok"),
                "ok_final": step.get("ok_final"),
                "actions": step.get("sim_actions"),
                "inference_calls": len(step.get("inference_rows") or []),
                "duration_s": (step.get("timing") or {}).get("execution_s"),
                "failure_code": step.get("failure_code"),
                "execute_horizon_policy": step.get("execute_horizon_policy"),
            }
        )
    return rows


def arm_summary(label: str, path: Path) -> dict[str, Any]:
    record = json.loads(path.read_text())
    record["__path__"] = str(path)
    composite = record.get("composite") or {}
    transport = None
    carrying = []
    for index, step in enumerate(record.get("steps") or [], start=1):
        carry = (step.get("goal_watch") or {}).get("carry") or {}
        if carry.get("object_n"):
            carrying.append((index, step, carry))
    # Step 1 carries the object into the container; step 2 carries the container
    # with the object sitting in it; a later step can carry a fixture that never
    # leaves the table. The transport segment is the carrying step with the
    # largest measured lift of its own carried body, which is a measurement, not
    # a guess about which step "looks like transport".
    best = None
    for index, step, carry in carrying:
        phase = phase_compare.analyse(record, index)
        lift = max(
            [row.get("lift_m") for row in phase["series"] if isinstance(row.get("lift_m"), (int, float))],
            default=0.0,
        )
        if best is None or lift > best[0]:
            best = (lift, index, carry, phase)
    if best:
        lift, index, carry, phase = best
        # The step is picked by "this step carried something", not by "the carry
        # went well": a transport arm whose container was lost mid-carry is
        # exactly the arm this report exists for.
        transport = {
            "step_index": index,
            "object_n": carry.get("object_n"),
            "held_through": carry.get("held_through"),
            "samples": phase["samples"],
            "noise": phase["noise"],
            "first_drift": phase["first_drift"],
            "final": phase["final"],
            "phase_spans": phase["phase_spans"],
            "chunks": phase["chunks"],
            "series": phase["series"],
        }
    return {
        "label": label,
        "record": str(path),
        "episode_id": record.get("episode_id"),
        "scene_seed": (record.get("env") or {}).get("seed"),
        "policy_seed": (record.get("sampling") or {}).get("policy_seed"),
        "initial_scene_fingerprint": record.get("initial_scene_fingerprint"),
        "initial_state_fingerprint": record.get("initial_state_fingerprint"),
        "initial_fixture_fingerprint": record.get("initial_fixture_fingerprint"),
        "failure_code": record.get("failure_code"),
        "user_goal_success": record.get("user_goal_success"),
        "final_all_goals_met": composite.get("final_all_goals_met"),
        "sim_actions_total": record.get("episode_sim_actions"),
        "duration_s": record.get("duration_s"),
        "steps": step_rows(record),
        "transport": transport,
        "transport_ready": composite.get("transport_ready"),
        "ready_to_transport": composite.get("ready_to_transport"),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--arm", action="append", required=True, metavar="LABEL=PATH")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    arms = []
    for spec in args.arm:
        label, _, path = spec.partition("=")
        arms.append(arm_summary(label or Path(path).stem, Path(path)))
    payload = {
        "schema": "embodied_engine.transport_ab.v1",
        "note": (
            "same scene_seed and policy_seed in both arms; the executed window differs only where "
            "execute_horizon_policy says so, so the two action streams are a closed-loop comparison, "
            "not two runs fed the same noise array"
        ),
        "arms": arms,
    }
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2))
    for arm in arms:
        first = (arm.get("transport") or {}).get("first_drift") or {}
        tail = (arm.get("transport") or {}).get("final") or {}
        print(
            f"[{arm['label']}] success={arm['user_goal_success']} code={arm['failure_code']} "
            f"actions={arm['sim_actions_total']} dur={arm['duration_s']} "
            f"held={((arm.get('transport') or {}).get('held_through'))} "
            f"final_xy={tail.get('rel_xy_m')} first={first.get('action')}({first.get('phase')})"
        )
    print(f"[ok] {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
